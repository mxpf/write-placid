import { writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { displayDate, projectRoot, readNowEntries, readPages, readPosts } from "./content.mjs";
import { writeRssFeed } from "./rss.mjs";
import { writeSitemap } from "./sitemap.mjs";

async function writeGeneratedModule(filename, sourceDirectory, exportName, value) {
  const output = `// Generated from content/${sourceDirectory}. Do not edit this file directly.\n\n` +
    `export const ${exportName} = ${JSON.stringify(value, null, 2)} as const;\n`;
  await writeFile(path.join(projectRoot, "app", filename), output, "utf8");
}

export async function generatePostsModule() {
  const includeDrafts = process.env.INCLUDE_DRAFTS === "1";
  const sourcePosts = await readPosts({ includeDrafts });
  const posts = sourcePosts.map((post) => ({
    title: post.title,
    slug: post.slug,
    date: displayDate(post.date),
    ...(post.updatedAt ? { updatedAt: displayDate(post.updatedAt.slice(0, 10)) } : {}),
    readingTime: post.readingTime,
    paragraphs: post.paragraphs,
    ...(post.source ? { source: post.source } : {}),
  }));

  await writeGeneratedModule("generated-posts.ts", "posts", "generatedPosts", posts);

  const sourceNowEntries = await readNowEntries({ includeDrafts });
  const nowEntries = sourceNowEntries.map((entry) => ({
    title: "Now",
    slug: entry.slug,
    date: displayDate(entry.date),
    paragraphs: entry.paragraphs,
  }));
  await writeGeneratedModule("generated-now.ts", "now", "generatedNowEntries", nowEntries);

  const pages = (await readPages()).map((page) => ({
    title: page.title,
    slug: page.slug,
    paragraphs: page.paragraphs,
  }));
  await writeGeneratedModule("generated-pages.ts", "pages", "generatedPages", pages);
  const publishedPosts = sourcePosts.filter((post) => post.status === "published");
  const publishedNowEntries = sourceNowEntries.filter((entry) => entry.status === "published");
  await Promise.all([
    writeRssFeed(publishedPosts, publishedNowEntries),
    writeSitemap(publishedPosts, pages),
  ]);
  return posts;
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  const posts = await generatePostsModule();
  const kind = process.env.INCLUDE_DRAFTS === "1" ? "staged" : "published";
  console.log(`Generated ${posts.length} ${kind} post${posts.length === 1 ? "" : "s"}.`);
}
